import base64
from collections.abc import Mapping
from dataclasses import dataclass

from anypatch.formats.xdelta_vectors_test_support import edited, moved, noise, text

N64_MAGIC = b"\x80\x37\x12\x40"
HEADER_REST = 0x3C
EVERY = ("ips", "ebp", "ups", "bps", "ppf", "aps", "rup", "bdf")
SHRINKABLE = ("ips", "ups", "bps", "aps", "rup", "bdf")
REARRANGED = ("bps", "bdf")


@dataclass(frozen=True, slots=True)
class Case:
    name: str
    source: bytes
    target: bytes
    formats: tuple[str, ...]


def n64(body: bytes) -> bytes:
    return N64_MAGIC + noise(HEADER_REST, 9) + body


def cases() -> list[Case]:
    small, wide = n64(text(8000, 21)), n64(text(70000, 23))
    return [
        Case("edit", small, edited(small, 31, 12), EVERY),
        Case("grow", small, small + text(3000, 32), EVERY),
        Case("shrink", small, small[:5000], SHRINKABLE),
        Case("moved", wide, moved(wide, 33), REARRANGED),
    ]


def names() -> list[str]:
    return [f"{case.name}.{kind}" for case in cases() for kind in case.formats]


def _decoded(chunks: tuple[str, ...]) -> bytes:
    return base64.b64decode("".join(chunks))


