import hashlib
import struct
import zlib

import pytest

from anypatch.formats import rup1

SOURCE = b"ABCDEFGHIJKLMNOP"
AFTER = b"ABxyEFGHIJKLMNOP!!"


def digests(data: bytes) -> bytes:
    crc = struct.pack(">I", zlib.crc32(data))
    return crc + hashlib.md5(data).digest() + hashlib.sha1(data).digest()


def binary(records: bytes, *, kind: int = 0, data: bytes = SOURCE) -> bytes:
    return b"NINJA1B " + bytes([kind]) + digests(data) + records + b"\x03EOF"


def text(lines: str, *, header: str | None = None) -> bytes:
    data = SOURCE
    first = header or (
        f"raw {zlib.crc32(data):08x} {hashlib.md5(data).hexdigest()} "
        f"{hashlib.sha1(data).hexdigest()}"
    )
    return f"NINJA1T\n#Generated by hand\n{first}\n{lines}".encode("ascii")


WORKED_RECORDS = b"\x01\x02\x01\x02xy" + b"\x01\x10\x01\x02!!"


class TestBinary:
    def test_each_record_writes_its_bytes_at_its_offset(self):
        # Arrange
        patch = binary(WORKED_RECORDS)

        # Act
        result = rup1.apply(SOURCE, patch)

        # Assert
        assert result == AFTER

    def test_a_compressed_body_is_zlib_as_ninja_writes_it(self):
        # Arrange
        body = binary(WORKED_RECORDS)[len(b"NINJA1B ") :]
        patch = b"NINJA1BZ" + zlib.compress(body, 9)

        # Act
        result = rup1.apply(SOURCE, patch)

        # Assert
        assert result == AFTER

    def test_all_zero_checksums_are_skipped(self):
        # Arrange
        patch = b"NINJA1B " + bytes(1 + 4 + 16 + 20) + WORKED_RECORDS + b"\x03EOF"

        # Act
        result = rup1.apply(b"something else, any size", patch)

        # Assert
        assert result[2:4] == b"xy"


class TestText:
    def test_comment_lines_are_skipped_and_records_are_hex(self):
        # Arrange
        patch = text("2 7879\n#a note\n10 2121")

        # Act
        result = rup1.apply(SOURCE, patch)

        # Assert
        assert result == AFTER

    def test_unknown_checksums_are_skipped(self):
        # Arrange
        patch = text("2 7879", header="raw unk unk unk")

        # Act
        result = rup1.apply(b"ZZZZ", patch)

        # Assert
        assert result == b"ZZxy"

    def test_a_compressed_text_body_is_zlib(self):
        # Arrange
        body = text("2 7879\n10 2121")[len(b"NINJA1T\n") :]
        patch = b"NINJA1TZ" + zlib.compress(body, 9)

        # Act
        result = rup1.apply(SOURCE, patch)

        # Assert
        assert result == AFTER


class TestSystems:
    def test_a_snes_patch_is_applied_to_the_headerless_rom_and_returns_it_headerless(self):
        # Arrange
        rom = bytearray(0x8000)
        rom[0x7FD5] = 0x20
        struct.pack_into("<HH", rom, 0x7FDC, 0x1234, 0xFFFF - 0x1234)
        plain = bytes(rom)
        patch = b"NINJA1B " + bytes([2]) + digests(plain) + b"\x01\x00\x01\x01Z" + b"\x03EOF"

        # Act
        result = rup1.apply(bytes(0x200) + plain, patch)

        # Assert
        assert result == b"Z" + plain[1:]

    def test_a_dump_the_system_cannot_read_is_compared_as_it_is(self):
        # Arrange
        patch = b"NINJA1B " + bytes([2]) + digests(SOURCE) + WORKED_RECORDS + b"\x03EOF"

        # Act
        result = rup1.apply(SOURCE, patch)

        # Assert
        assert result == AFTER


class TestLargeFiles:
    def test_a_dump_past_30_mib_is_checked_by_its_sample(self):
        # Arrange
        size = 0x1E00000 + 16
        dump = bytes(size)
        sample = dump[:0x1400000] + dump[-0xA00000:] + str(size).encode("ascii")
        patch = b"NINJA1B " + bytes([0]) + digests(sample) + b"\x01\x00\x01\x01Z" + b"\x03EOF"

        # Act
        result = rup1.apply(dump, patch)

        # Assert
        assert result[:2] == b"Z\x00"
        assert len(result) == size


class TestRefusals:
    @pytest.mark.parametrize(
        ("patch", "message"),
        [
            (b"NINJA2", "not a NINJA 1 patch"),
            (b"NINJA1X?", "NINJA 1 mode b'X?'; only binary, text and their zlib forms are read"),
            (b"NINJA1B " + bytes(10), "the patch ends inside its 41-byte header"),
            (binary(b"\x01\x02\x01\x05ab")[:-4], "the patch ends inside a record"),
            (binary(b"")[:-4], "the patch has no EOF record"),
            (b"NINJA1BZ" + b"not zlib", "the compressed body does not decompress"),
            (text("2 7879", header="raw 00000000 unk unk"), "CRC32 00000000"),
            (text("zz 7879"), "the line 'zz 7879' is not a hex offset and hex bytes"),
            (b"NINJA1T\n#only a comment\n", "the patch has no header line"),
            (binary(b"\x02\x00")[:-4], "the patch ends inside a record at byte"),
        ],
        ids=[
            "magic",
            "mode",
            "short-header",
            "short-record",
            "no-eof",
            "bad-zlib",
            "checksum",
            "bad-line",
            "no-header",
            "short-number",
        ],
    )
    def test_a_damaged_or_mismatched_patch_is_refused(self, patch, message):
        # Arrange
        source = SOURCE

        # Act
        with pytest.raises(rup1.Rup1Error) as raised:
            rup1.apply(source, patch)

        # Assert
        assert message in str(raised.value)

    def test_a_compressed_body_past_the_ceiling_is_refused(self, monkeypatch):
        # Arrange
        monkeypatch.setattr(rup1, "BODY_LIMIT", 100)
        patch = b"NINJA1TZ" + zlib.compress(b"#" * 1000)

        # Act
        with pytest.raises(rup1.Rup1Error) as raised:
            rup1.apply(SOURCE, patch)

        # Assert
        assert "decompresses past 100 bytes" in str(raised.value)


class TestWriting:
    def test_a_binary_patch_with_minimal_widths_is_written(self):
        # Arrange
        after = AFTER

        # Act
        patch = rup1.build(SOURCE, after)

        # Assert
        assert patch == binary(WORKED_RECORDS)

    def test_a_record_at_the_eof_offset_takes_four_bytes(self):
        # Arrange
        at = rup1.END_AS_OFFSET
        before = bytes(at + 4)
        after = before[:at] + b"\x01" + before[at + 1 :]

        # Act
        patch = rup1.build(before, after)

        # Assert
        assert b"\x04\x00\x45\x4f\x46\x01\x01\x01" in patch
        assert rup1.apply(before, patch) == after

    def test_a_shrink_is_refused(self):
        # Arrange
        after = SOURCE[:4]

        # Act
        with pytest.raises(rup1.Rup1Error) as raised:
            rup1.build(SOURCE, after)

        # Assert
        assert str(raised.value) == (
            "NINJA 1 records only overwrite and extend, so it cannot shrink a file"
        )


class TestARecordAtTheEofOffset:
    def test_one_ninja_wrote_in_three_bytes_is_read_as_a_record(self):
        # Arrange
        at = rup1.END_AS_OFFSET
        before = bytes(at + 2)
        record = b"\x03" + at.to_bytes(3, "big") + b"\x01\x01Z"
        patch = b"NINJA1B " + bytes(41) + record + b"\x03EOF"

        # Act
        result = rup1.apply(before, patch)

        # Assert
        assert result[at - 1 : at + 2] == b"\x00Z\x00"
